def normalize_model_name(brand_name: str, model_name: str) -> str:
    """Strip a redundant leading brand prefix from a model label."""
    prefixes = (f"{brand_name} ", f"{brand_name}‌")
    for prefix in prefixes:
        if model_name.startswith(prefix):
            return model_name[len(prefix) :].strip()
    return model_name
